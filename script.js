let currentLang = 'en';

function applyLanguage(lang) {
    const t = translations[lang];

    // Update html element direction and language
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr';

    // Update page title
    document.title = t['page-title'];

    // Update elements with text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (t[key] !== undefined) {
            el.textContent = t[key];
        }
    });

    // Update elements with HTML content
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.dataset.i18nHtml;
        if (t[key] !== undefined) {
            el.innerHTML = t[key];
        }
    });

    // Update alt attributes
    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
        const key = el.dataset.i18nAlt;
        if (t[key] !== undefined) {
            el.alt = t[key];
        }
    });

    // Update active state on lang buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    // Persist language in URL query param (?lang=en); omit param for default Hebrew
    const params = new URLSearchParams(window.location.search);
    if (lang === 'he') {
        params.delete('lang');
    } else {
        params.set('lang', lang);
    }
    const newSearch = params.toString() ? '?' + params.toString() : '';
    history.replaceState(null, '', window.location.pathname + newSearch + window.location.hash);

    currentLang = lang;
}

document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
        if (btn.dataset.lang !== currentLang) {
            applyLanguage(btn.dataset.lang);
        }
    });
});

// Initialize language from URL on page load
const urlLang = new URLSearchParams(window.location.search).get('lang');
if (urlLang === 'en' || urlLang === 'he') {
    applyLanguage(urlLang);
}

// Scroll Reveal Animation
const observerOptions = {
    threshold: 0.1
};

const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.classList.add('active');
        }
    });
}, observerOptions);

document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

// Expandable aspect cards
document.querySelectorAll('.aspect-card--expandable').forEach(card => {
    const toggle = () => {
        const expanded = card.getAttribute('aria-expanded') === 'true';
        card.setAttribute('aria-expanded', String(!expanded));
    };
    card.addEventListener('click', toggle);
    card.addEventListener('keydown', e => {
        if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); toggle(); }
    });
});

